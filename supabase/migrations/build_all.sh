#!/usr/bin/env bash
# Joins the numbered migrations (0001, 0002, ...) in order into ALL_new_site.sql. Run from this folder.
set -e
cd "$(dirname "$0")"
out=ALL_new_site.sql
echo "-- ALL_new_site.sql: generated by build_all.sh from the numbered files below. Do not edit; edit the numbered file and rebuild." > $out
for f in [0-9][0-9][0-9][0-9]_*.sql; do
  printf '\n-- ======================================================================\n-- FILE: %s\n-- ======================================================================\n' "$f" >> $out
  cat "$f" >> $out
done
echo "built $out from $(ls [0-9][0-9][0-9][0-9]_*.sql | wc -l) files"
